// The OFFICIAL demo (Space Apps Project Submission Guide, 13 Nov 2026): a video of 30 seconds or less, or a deck of at most
// seven slides including the title. Over either limit = not eligible for Global Judging. These tests keep both inside the
// limits and keep the SI marking, the team facts and the NASA numbers honest.
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { inflateRawSync } from 'node:zlib';
import { describe, expect, it } from 'vitest';
import moon from '@/data/snapshots/moon-facts.json';

const read = (p: string): string => readFileSync(p, 'utf8');
const walk = (d: string): string[] => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));
const SOURCE = walk('src').filter((f) => f.endsWith('.ts')).map(read).join('\n');
const words = (s: string): number => (s.match(/[A-Za-z0-9'’-]+/g) ?? []).length;
const norm = (s: string): string => s.replace(/\s+/g, ' ').trim();
// Words on a slide: whitespace-separated tokens, so "0.00490" and "km³/s²" each count as one word (a stricter and more natural count).
const slideWords = (s: string): number => s.split(/\s+/).filter(Boolean).length;
const FOOTER = 'Built with SI assistance (Claude, Anthropic)';

// ---- the 30-second video script and its captions ----------------------------------------------------------------
const script = read('docs/demo/demo-30s.md');
interface Row { start: number; end: number; vo: string }
const rows: Row[] = [...script.matchAll(/^\| (\d):(\d{2})-(\d):(\d{2}) \| .*? \| "(.*)" \|$/gm)].map((m) => ({
  start: Number(m[1]) * 60 + Number(m[2]), end: Number(m[3]) * 60 + Number(m[4]), vo: m[5] as string,
}));
interface Cue { n: number; start: number; end: number; lines: string[] }
const toS = (h: string, m: string, s: string, ms: string): number => Number(h) * 3600 + Number(m) * 60 + Number(s) + Number(ms) / 1000;
const cues: Cue[] = read('docs/demo/demo-30s.srt').trim().split(/\n\s*\n/).map((block) => {
  const [n, time, ...lines] = block.split('\n');
  const m = /^(\d\d):(\d\d):(\d\d),(\d{3}) --> (\d\d):(\d\d):(\d\d),(\d{3})$/.exec(time ?? '');
  if (!m) throw new Error(`bad timing line: ${String(time)}`);
  return { n: Number(n), start: toS(m[1]!, m[2]!, m[3]!, m[4]!), end: toS(m[5]!, m[6]!, m[7]!, m[8]!), lines };
});

describe('demo-30s.md: the 30-second video script', () => {
  it('follows the guide timeline (0:00, 0:02, 0:05, 0:10, 0:20) and ends at 30 seconds or less', () => {
    expect(rows.map((r) => r.start)).toEqual([0, 2, 5, 10, 20]);
    expect(rows.at(-1)!.end).toBeLessThanOrEqual(30);
    for (let i = 1; i < rows.length; i++) expect(rows[i]!.start).toBe(rows[i - 1]!.end); // no gaps, no overlap
  });
  it('is at most 75 spoken words in all, and the script states the true count', () => {
    const total = rows.reduce((n, r) => n + words(r.vo), 0);
    expect(total).toBeLessThanOrEqual(75);
    expect(script).toContain(`**${total} words**`);
  });
  it('never needs more than 2.7 spoken words per second in any row (and 2.7 over the whole 30 s)', () => {
    for (const r of rows) expect(words(r.vo) / (r.end - r.start), `row ${r.start}-${r.end}`).toBeLessThanOrEqual(2.7);
    expect(rows.reduce((n, r) => n + words(r.vo), 0) / rows.at(-1)!.end).toBeLessThanOrEqual(2.7);
  });
  it('introduces the speaker and team, names the challenge, gives the title and tagline, and cites the one NASA data source', () => {
    const vo = rows.map((r) => r.vo).join(' ');
    for (const s of ['Sagar', 'team Threadline', 'Space Mission Design Game', 'Every choice leaves a trace', "NASA's Moon Fact Sheet"]) expect(vo, s).toContain(s);
  });
  it('states the official limits, the one-link rule, the SI watermark rule and the under-18 rule', () => {
    for (const s of ['30 seconds or less', 'seven slides', 'will not be eligible for Global Judging', '**one** demo link', FOOTER, 'under 18', 'English']) expect(script, s).toContain(s);
  });
  it('quotes only labels that exist in the game, and matches ?demo=1', () => {
    expect(script).toContain('/?demo=1');
    expect(script).toContain('Seed **29**');
    const bold = [...script.matchAll(/\*\*([^*]+)\*\*/g)].map((m) => m[1] as string);
    const clickable = ['Try the 90-second demo', 'Thermal infrared radiometer', 'Skip to the outcome', 'Exit the demo', 'Start mission'];
    for (const c of clickable) {
      expect(bold, c).toContain(c);
      expect(SOURCE, `${c} must exist in src`).toContain(c);
    }
  });
  it('says nothing about who had the idea or who wrote the game', () => {
    expect(script).not.toMatch(/the AI (wrote|had|came up)|we came up with|my idea|our idea|written by (an )?AI|generated by/i);
  });
});

describe('demo-30s.srt: English captions', () => {
  it('is well formed: numbered in order, no overlap, ends within 30 seconds', () => {
    expect(cues.map((c) => c.n)).toEqual(cues.map((_, i) => i + 1));
    for (const c of cues) expect(c.end).toBeGreaterThan(c.start);
    for (let i = 1; i < cues.length; i++) expect(cues[i]!.start).toBeGreaterThanOrEqual(cues[i - 1]!.end);
    expect(cues.at(-1)!.end).toBeLessThanOrEqual(30);
  });
  it('follows the caption rules: at most 2 lines of 42 characters, 1 to 7 seconds, 20 characters per second', () => {
    for (const c of cues) {
      expect(c.lines.length, `cue ${c.n}`).toBeLessThanOrEqual(2);
      for (const l of c.lines) expect(l.length, `cue ${c.n}: ${l}`).toBeLessThanOrEqual(42);
      const d = c.end - c.start;
      expect(d, `cue ${c.n}`).toBeGreaterThanOrEqual(1);
      expect(d, `cue ${c.n}`).toBeLessThanOrEqual(7);
      expect(c.lines.join(' ').length / d, `cue ${c.n} reading speed`).toBeLessThanOrEqual(20);
    }
  });
  it('says exactly what the voice-over says: the cues inside each row spell out that row, word for word', () => {
    for (const r of rows) {
      const inside = cues.filter((c) => c.start >= r.start && c.end <= r.end);
      expect(norm(inside.map((c) => c.lines.join(' ')).join(' ')), `row ${r.start}-${r.end}`).toBe(norm(r.vo));
    }
    for (const c of cues) expect(rows.some((r) => c.start >= r.start && c.end <= r.end), `cue ${c.n} must sit inside one row`).toBe(true);
  });
});


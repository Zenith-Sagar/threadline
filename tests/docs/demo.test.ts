// A minimal zip reader (central directory + raw inflate), so the test needs no extra dependency.
function unzip(path: string): Map<string, Buffer> {
  const b = readFileSync(path);
  let eocd = b.length - 22;
  while (eocd >= 0 && b.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw new Error('not a zip file');
  const count = b.readUInt16LE(eocd + 10);
  let p = b.readUInt32LE(eocd + 16);
  const out = new Map<string, Buffer>();
  for (let i = 0; i < count; i++) {
    const method = b.readUInt16LE(p + 10);
    const csize = b.readUInt32LE(p + 20);
    const nlen = b.readUInt16LE(p + 28), xlen = b.readUInt16LE(p + 30), clen = b.readUInt16LE(p + 32);
    const local = b.readUInt32LE(p + 42);
    const name = b.toString('utf8', p + 46, p + 46 + nlen);
    const ds = local + 30 + b.readUInt16LE(local + 26) + b.readUInt16LE(local + 28);
    const raw = b.subarray(ds, ds + csize);
    out.set(name, method === 0 ? Buffer.from(raw) : inflateRawSync(raw));
    p += 46 + nlen + xlen + clen;
  }
  return out;
}
const textOf = (xml: string): string => [...xml.matchAll(/<a:t>([^<]*)<\/a:t>/g)].map((m) => m[1] as string).join(' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');

const PPTX = 'docs/demo/threadline-demo-7slides.pptx';
const PDF = 'docs/demo/threadline-demo-7slides.pdf';
const deck = unzip(PPTX);
const slideNames = [...deck.keys()].filter((n) => /^ppt\/slides\/slide\d+\.xml$/.test(n)).sort((a, b) => Number(/(\d+)\.xml/.exec(a)![1]) - Number(/(\d+)\.xml/.exec(b)![1]));
const slideText = slideNames.map((n) => textOf(deck.get(n)!.toString('utf8')));

describe('the 7-slide deck (.pptx)', () => {
  it('has exactly 7 slides, title slide included (the limit is 7)', () => {
    expect(slideNames).toHaveLength(7);
  });
  it('keeps every slide to 30 words of content or fewer (the footer is on the layout and is not counted)', () => {
    slideText.forEach((t, i) => expect(slideWords(t), `slide ${i + 1}: ${t}`).toBeLessThanOrEqual(30));
    slideText.forEach((t, i) => expect(slideWords(t), `slide ${i + 1}`).toBeGreaterThan(3));
  });
  it('carries the footer "Built with SI assistance (Claude, Anthropic)" on the layout of every slide', () => {
    for (const n of slideNames) {
      const rels = deck.get(n.replace('slides/', 'slides/_rels/') + '.rels')!.toString('utf8');
      const layout = /Target="\.\.\/slideLayouts\/(slideLayout\d+\.xml)"/.exec(rels)?.[1];
      expect(layout, `${n} has a layout`).toBeTruthy();
      expect(textOf(deck.get(`ppt/slideLayouts/${layout}`)!.toString('utf8')), `${n} layout footer`).toContain(FOOTER);
    }
  });
  it('slide 1: title, tagline, team name, member (Sagar only) and the challenge; the AI is not listed as a member', () => {
    const t = slideText[0]!;
    for (const s of ['Threadline', 'Every choice leaves a trace', 'Team', 'Member', 'Sagar', 'Challenge', 'Space Mission Design Game']) expect(t, s).toContain(s);
    for (const t2 of slideText) expect(t2).not.toMatch(/Claude|Anthropic/);
    expect(t).toMatch(/Not affiliated with NASA/);
  });
  it('slides 1, 3 and 4 show a real screenshot; the images are the five SI-marked captures and nothing else (no logos)', () => {
    const media = [...deck.keys()].filter((n) => n.startsWith('ppt/media/'));
    expect(media.length).toBeGreaterThanOrEqual(3);
    expect(media.length).toBeLessThanOrEqual(5);
    for (const i of [1, 3, 4]) expect(deck.get(`ppt/slides/_rels/slide${i}.xml.rels`)!.toString('utf8'), `slide ${i}`).toMatch(/relationships\/image/);
    expect(existsSync('submission/screenshots-si/02-design-bay-threads.png')).toBe(true);
  });
  it('slide 5 states the three Moon Fact Sheet values exactly as the game uses them, and the four mission segments as structure only', () => {
    const t = slideText[4]!;
    expect(t).toContain(String(moon.values.volumetricMeanRadiusKm));
    expect(t).toContain('0.00490');
    expect(t).toContain(String(moon.values.semimajorAxisE6Km));
    expect(moon.values.gmE6Km3S2).toBe(0.0049);
    for (const s of ['Moon Fact Sheet', 'Launch', 'Space', 'Ground', 'User', 'structure only']) expect(t, s).toContain(s);
    expect(t).not.toMatch(/GMAT|Mission Viz|Concept Maturity|Mission Design Lab|CubeSat/); // resources the owner has not confirmed using
  });
  it('slide 6 shows the three labels the game uses', () => {
    for (const s of ['NASA DATA', 'SIMPLIFIED PHYSICS', 'GAME MODEL']) expect(slideText[5]!, s).toContain(s);
  });
  it('slide 7 is the live link: a URL when one was built in, or a visible [OWNER: ...] placeholder (never an invented URL)', () => {
    const t = slideText[6]!;
    expect(/https:\/\/\S+/.test(t) || /\[OWNER: add the live link\]/.test(t)).toBe(true);
  });
  it('carries the SI acknowledgment in its metadata (document subject)', () => {
    const core = deck.get('docProps/core.xml')!.toString('utf8');
    expect(core).toMatch(/<dc:subject>[^<]*Built with SI assistance \(Claude, Anthropic\)/);
    expect(core).toMatch(/<dc:creator>Team Threadline \(Sagar\)<\/dc:creator>/);
  });
});

describe('the 7-slide deck (.pdf)', () => {
  const pdf = readFileSync(PDF);
  const head = pdf.toString('latin1');
  it('is a real PDF with exactly 7 pages', () => {
    expect(head.startsWith('%PDF')).toBe(true);
    expect((head.match(/\/Type\s*\/Page(?![a-z])/g) ?? []).length).toBe(7);
  });
  it('carries the SI acknowledgment in its metadata and is small enough to host anywhere', () => {
    // The Subject entry is a plain string (written by scripts/finish-demo-pdf.py). Boolean checks: a failure must not dump binary.
    expect(/\/Subject \([^)]*Built with SI assistance/.test(head), 'PDF /Subject names SI assistance').toBe(true);
    expect(/\/Keywords \([^)]*SI(-|\\055)assisted/.test(head), 'PDF /Keywords names SI').toBe(true);
    expect(pdf.length).toBeLessThan(5 * 1024 * 1024);
  });
});

// Permanent balance test (Phase 3). Real simulate() over 8,640 designs x 12 storm seeds x 3 responses.
// If you retune src/content and this fails, the game lost a strategy, grew a dominant design,
// or made one storm response always right or always wrong.
//
//   npm run sweep                  prints the report
//   SWEEP_WRITE=1 npm run sweep    also writes docs/balance-sweep.md
import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { LUNAR_RECON } from '@/content';
import {
  ARRAY_STEPS, BATTERY_STEPS, FUEL_MARGINS, STORAGE_STEPS, formatReport, runSweep, summarize,
  type SweepRow,
} from './sweep';

const data = runSweep();
const s = summarize(data);
const rows = data.rows;
const triple = (r: SweepRow): string => [...r.design.instruments].sort().join('+');
const key = (r: SweepRow): string => `${triple(r)}/${r.design.vehicle}`;

if (process.env['SWEEP']) {
  const report = formatReport(data, s);
  console.log('\nBALANCE SWEEP\n' + report + '\n');
  if (process.env['SWEEP_WRITE']) {
    writeFileSync(
      'docs/balance-sweep.md',
      `# Balance sweep (Phase 3)\n\nGenerated by \`SWEEP_WRITE=1 npm run sweep\`. GAME MODEL values from src/content. Includes the storm, the data channel (storage) and all three storm responses.\n\n${report}\n`,
    );
  }
}

describe('balance sweep (Phase 3)', () => {
  it('covers the whole grid', () => {
    expect(rows).toHaveLength(
      20 * 3 * BATTERY_STEPS.length * ARRAY_STEPS.length * FUEL_MARGINS.length * STORAGE_STEPS.length,
    );
    expect(data.seeds).toHaveLength(12);
  });

  it('is neither trivial nor impossible', () => {
    const validFrac = s.valid / s.total;
    const viableFrac = s.viable / s.total;
    expect(validFrac).toBeGreaterThan(0.3);
    expect(validFrac).toBeLessThan(0.8);
    expect(viableFrac).toBeGreaterThan(0.1);
    expect(viableFrac).toBeLessThan(0.7);
  });

  it('finds three distinct viable archetypes', () => {
    const { lean, scienceHeavy, robust } = s.best;
    for (const r of [lean, scienceHeavy, robust]) expect(r.meanComposite).toBeGreaterThanOrEqual(55);
    expect(new Set([triple(lean), triple(scienceHeavy), triple(robust)]).size).toBe(3);
  });

  it('each archetype clearly wins its own axis', () => {
    const { lean, scienceHeavy, robust } = s.best;
    expect(scienceHeavy.expectedScience).toBeGreaterThanOrEqual(lean.expectedScience * 1.15);
    expect(lean.costM).toBeLessThanOrEqual(scienceHeavy.costM * 0.85);
    expect(lean.efficiency).toBeGreaterThan(scienceHeavy.efficiency * 1.03);
    expect(robust.robustness).toBeGreaterThan(Math.max(lean.robustness, scienceHeavy.robustness) * 1.1);
  });

  it('has no dominant design: different designs win cost, science and robustness', () => {
    const viable = rows.filter((r) => r.valid && r.meanComposite >= 55);
    const cheapest = viable.reduce((a, b) => (b.costM < a.costM ? b : a));
    const mostScience = rows.filter((r) => r.valid).reduce((a, b) => (b.expectedScience > a.expectedScience ? b : a));
    const mostRobust = viable.reduce((a, b) => (b.robustness > a.robustness ? b : a));
    expect(new Set([cheapest.label, mostScience.label, mostRobust.label]).size).toBe(3);
    // And no single design is the best of two archetypes at once.
    const names = [s.best.lean.label, s.best.scienceHeavy.label, s.best.robust.label];
    expect(new Set(names).size).toBe(3);
  });

  it('has a wide Pareto front of real trade-offs', () => {
    expect(s.paretoFront.length).toBeGreaterThanOrEqual(10);
    expect(new Set(s.paretoFront.map(key)).size).toBeGreaterThanOrEqual(8);
  });

  it('has no trap parts: every instrument, launcher and storage size appears in a viable design', () => {
    const viable = rows.filter((r) => r.valid && r.meanComposite >= 55);
    for (const i of LUNAR_RECON.instruments) {
      expect(viable.some((r) => r.design.instruments.includes(i.id)), `instrument ${i.id}`).toBe(true);
    }
    for (const v of LUNAR_RECON.vehicles) expect(viable.some((r) => r.design.vehicle === v.id), `launcher ${v.id}`).toBe(true);
    for (const st of STORAGE_STEPS) expect(viable.some((r) => r.design.storageMb === st), `storage ${st}`).toBe(true);
  });

  it('every storm response is clearly the best choice in a meaningful share of situations', () => {
    for (const id of ['ride-out', 'shed-heaviest', 'safe-mode'] as const) {
      expect(s.responseBest[id] / s.situationCount, `response ${id}`).toBeGreaterThan(0.05);
      expect(s.responseBest[id] / s.situationCount, `response ${id}`).toBeLessThan(0.7);
    }
  });

  it('keeps radar a demanding but playable choice', () => {
    const radar = rows.filter((r) => r.valid && r.design.instruments.includes('radar'));
    const good = radar.filter((r) => r.meanComposite >= 55).length;
    expect(good).toBeGreaterThan(0);
    expect(good / radar.length).toBeLessThan(0.6);
  });
}, 120_000);

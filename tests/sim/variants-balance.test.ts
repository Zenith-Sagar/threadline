// Slice B: every mission variant must stay a real game. Same sweep harness, same thresholds as balance.test.ts:
// at least three viable archetypes, no dominant design, and every storm response clearly best somewhere.
// SWEEP=1 prints the tables; SWEEP_WRITE=1 also writes docs/balance-variants.md.
import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { LUNAR_RECON } from '@/content';
import { VARIANTS, applyVariant } from '@/content/variants';
import { formatReport, runSweep, summarize, type SweepRow } from './sweep';

const triple = (r: SweepRow): string => [...r.design.instruments].sort().join('+');
const reports: string[] = [];

for (const variant of VARIANTS.filter((v) => v.id !== 'standard')) {
  const mission = applyVariant(LUNAR_RECON, variant.id);
  const data = runSweep(mission);
  const s = summarize(data);
  reports.push(`## ${variant.name} (${variant.change(LUNAR_RECON)})\n\n${formatReport(data, s)}\n`);

  describe(`balance sweep: ${variant.name}`, () => {
    it('is neither trivial nor impossible', () => {
      const validFrac = s.valid / s.total;
      const viableFrac = s.viable / s.total;
      expect(validFrac).toBeGreaterThan(0.15);
      expect(validFrac).toBeLessThan(0.85);
      expect(viableFrac).toBeGreaterThan(0.05);
      expect(viableFrac).toBeLessThan(0.7);
    });

    it('has three distinct viable archetypes, each clearly winning its own axis', () => {
      const { lean, scienceHeavy, robust } = s.best;
      for (const r of [lean, scienceHeavy, robust]) expect(r.meanComposite).toBeGreaterThanOrEqual(55);
      expect(new Set([triple(lean), triple(scienceHeavy), triple(robust)]).size).toBe(3);
      expect(scienceHeavy.expectedScience).toBeGreaterThan(lean.expectedScience * 1.05);
      expect(lean.costM).toBeLessThan(scienceHeavy.costM);
      expect(robust.robustness).toBeGreaterThan(Math.max(lean.robustness, scienceHeavy.robustness) * 1.05);
    });

    it('has no dominant design: three different designs win cost, science and robustness', () => {
      const names = [s.best.lean.label, s.best.scienceHeavy.label, s.best.robust.label];
      expect(new Set(names).size).toBe(3);
      expect(s.paretoFront.length).toBeGreaterThanOrEqual(5);
    });

    it('every storm response is clearly the best choice in a meaningful share of situations', () => {
      for (const id of ['ride-out', 'shed-heaviest', 'safe-mode'] as const) {
        expect(s.responseBest[id] / s.situationCount, `response ${id}`).toBeGreaterThan(0.05);
        expect(s.responseBest[id] / s.situationCount, `response ${id}`).toBeLessThan(0.7);
      }
    });
  });
}

if (process.env['SWEEP']) {
  console.log('\nVARIANT SWEEPS\n' + reports.join('\n'));
  if (process.env['SWEEP_WRITE']) {
    writeFileSync(
      'docs/balance-variants.md',
      `# Balance sweeps for the mission variants (Phase 5)\n\nGenerated by \`SWEEP=1 SWEEP_WRITE=1 npx vitest run tests/sim/variants-balance.test.ts\`. GAME MODEL values. Each variant runs through the same simulate().\n\n${reports.join('\n')}`,
    );
  }
}
